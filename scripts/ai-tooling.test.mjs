// @vitest-environment node
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
const fixture = vi.hoisted(() => ({ root: "" }));
// Resolve the script's installation directory into a temporary checkout so the
// real sync code can write output without changing this repository's catalog.
vi.mock("node:url", async (original) => {
  const actual = await original();
  return {
    ...actual,
    fileURLToPath: (value, ...rest) =>
      String(value).endsWith("/scripts/sync-ai.mjs") && fixture.root
        ? path.join(fixture.root, "scripts/sync-ai.mjs")
        : actual.fileURLToPath(value, ...rest),
  };
});
const repo = process.cwd();
const originalArgv = process.argv;
let catalog;
async function write(relative, value) {
  const file = path.join(fixture.root, relative);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, typeof value === "string" ? value : JSON.stringify(value));
  return file;
}
async function run(script, ...args) {
  vi.resetModules();
  process.argv = [process.execPath, path.join(repo, "scripts", script), ...args];
  await import(/* @vite-ignore */ path.join(repo, "scripts", script));
}
beforeEach(async () => {
  fixture.root = await mkdtemp(path.join(os.tmpdir(), "latexdo-ai-tooling-"));
  catalog = JSON.parse(
    await readFile(path.join(repo, "catalog/latexdo-ai-catalog.v1.json"), "utf8"),
  );
  vi.spyOn(process, "cwd").mockReturnValue(fixture.root);
  vi.spyOn(console, "log").mockImplementation(() => {});
  vi.spyOn(console, "warn").mockImplementation(() => {});
  vi.spyOn(console, "error").mockImplementation(() => {});
  vi.spyOn(process, "exit").mockImplementation((code) => {
    throw new Error(`exit ${code}`);
  });
  for (const key of [
    "LATEXDO_AI_SOURCE_PATH",
    "LATEXDO_AI_CATALOG_PATH",
    "LATEXDO_AI_CATALOG_URL",
    "LATEXDO_AI_CATALOG_REQUIRED",
  ])
    vi.stubEnv(key, "");
});
afterEach(async () => {
  process.argv = originalArgv;
  vi.unstubAllEnvs();
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
  await rm(fixture.root, { recursive: true, force: true });
  fixture.root = "";
});
describe("AI catalog validation and generation", () => {
  it("validates the real catalog and generates its typed runtime module", async () => {
    const source = await write("catalog/latexdo-ai-catalog.v1.json", catalog);
    await run("validate-catalog.mjs", source);
    await run("sync-ai.mjs");
    const generated = await readFile(
      path.join(fixture.root, "src/features/ai/aiCatalog.generated.ts"),
      "utf8",
    );
    expect(generated).toContain("satisfies AiCatalog");
    expect(generated).toContain(catalog.defaultLocalModelId);
    expect(generated).toContain(catalog.defaultCloudProviderId);
    expect(generated).toContain("Generated by scripts/sync-ai.mjs");
  });
  it.each([
    null,
    {},
    { schemaVersion: 2, localModels: [], cloudProviders: [] },
    "bad-model",
    "bad-provider",
    "duplicate",
    "bad-defaults",
  ])("rejects malformed catalog %j in both entry points", async (variant) => {
    let invalid = variant;
    if (variant === "bad-model")
      invalid = {
        ...catalog,
        localModels: [
          {
            id: "same",
            tier: "invalid",
            downloadUrl: "http://insecure",
            minSystemRamGb: -1,
            minAvailableRamGb: -1,
            supportsTools: "yes",
            strengths: [1],
          },
        ],
      };
    if (variant === "bad-provider")
      invalid = {
        ...catalog,
        cloudProviders: [
          {
            id: "bad",
            apiShape: "invalid",
            baseUrl: "not-url",
            apiKeyUrl: 1,
            custom: "yes",
            models: [1],
          },
        ],
      };
    if (variant === "duplicate")
      invalid = {
        ...catalog,
        localModels: [catalog.localModels[0], catalog.localModels[0]],
        cloudProviders: [catalog.cloudProviders[0], catalog.cloudProviders[0]],
      };
    if (variant === "bad-defaults")
      invalid = {
        ...catalog,
        defaultLocalModelId: "missing",
        defaultInlineModelId: "missing",
        defaultCloudProviderId: "missing",
      };
    const source = await write(
      "catalog/latexdo-ai-catalog.v1.json",
      JSON.stringify(invalid),
    );
    await expect(run("validate-catalog.mjs", source)).rejects.toThrow("exit 1");
    await expect(run("sync-ai.mjs")).rejects.toThrow("Invalid LatexDo AI catalog");
    await expect(
      readFile(path.join(fixture.root, "src/features/ai/aiCatalog.generated.ts")),
    ).rejects.toThrow();
  });
  it("fetches an explicitly configured catalog and reports HTTP failures", async () => {
    vi.stubEnv("LATEXDO_AI_CATALOG_URL", "https://catalog.example.invalid/ai.json");
    const fetchMock = vi
      .fn()
      .mockResolvedValueOnce(new Response(JSON.stringify(catalog)))
      .mockResolvedValueOnce(new Response("down", { status: 503 }));
    vi.stubGlobal("fetch", fetchMock);
    await run("sync-ai.mjs");
    expect(
      await readFile(
        path.join(fixture.root, "src/features/ai/aiCatalog.generated.ts"),
        "utf8",
      ),
    ).toContain("https://catalog.example.invalid/ai.json");
    await expect(run("sync-ai.mjs")).rejects.toThrow("HTTP 503");
  });
  it("preserves checked-in output when an optional catalog is missing and fails for a required one", async () => {
    await write("src/features/ai/aiCatalog.generated.ts", "keep existing");
    await run("sync-ai.mjs");
    expect(
      await readFile(
        path.join(fixture.root, "src/features/ai/aiCatalog.generated.ts"),
        "utf8",
      ),
    ).toBe("keep existing");
    vi.stubEnv("LATEXDO_AI_CATALOG_REQUIRED", "1");
    await expect(run("sync-ai.mjs")).rejects.toThrow("No AI catalog");
    vi.stubEnv("LATEXDO_AI_CATALOG_PATH", path.join(fixture.root, "missing.json"));
    await expect(run("sync-ai.mjs")).rejects.toThrow("No AI catalog");
  });
});
describe("runtime source synchronization", () => {
  it("copies runtime source and replaces only the marked stylesheet section", async () => {
    const sourceRoot = path.join(fixture.root, "upstream");
    vi.stubEnv("LATEXDO_AI_SOURCE_PATH", sourceRoot);
    const manifest = {
      schemaVersion: 1,
      files: [{ from: "runtime.ts", to: "src/runtime.ts" }],
      styleFragments: [
        {
          from: "fragment.css",
          to: "src/style.css",
          startMarker: "/* AI */",
          endMarker: "/* END */",
        },
      ],
    };
    await write("upstream/latexdo-sync.json", manifest);
    await write("upstream/runtime.ts", "export const runtime = 42;");
    await write("upstream/fragment.css", "/* AI */\n.new { color: red; }\n");
    await write("src/style.css", "before\n/* AI */\nold\n/* END */\nafter");
    await write("upstream/catalog/latexdo-ai-catalog.v1.json", catalog);
    await run("sync-ai.mjs");
    expect(await readFile(path.join(fixture.root, "src/runtime.ts"), "utf8")).toBe(
      "export const runtime = 42;",
    );
    expect(await readFile(path.join(fixture.root, "src/style.css"), "utf8")).toBe(
      "before\n/* AI */\n.new { color: red; }\n\n/* END */\nafter",
    );
  });
  it.each([
    null,
    { schemaVersion: 2 },
    { schemaVersion: 1, files: null },
    { schemaVersion: 1, files: [null] },
    { schemaVersion: 1, files: [{ from: "../outside", to: "safe.ts" }] },
    { schemaVersion: 1, files: [{ from: "a", to: "" }] },
    { schemaVersion: 1, files: [], styleFragments: [null] },
    { schemaVersion: 1, files: [], styleFragments: [{ from: "a", to: "b" }] },
  ])("rejects invalid sync manifests before copying %j", async (manifest) => {
    vi.stubEnv("LATEXDO_AI_SOURCE_PATH", path.join(fixture.root, "upstream"));
    await write("upstream/latexdo-sync.json", JSON.stringify(manifest));
    await expect(run("sync-ai.mjs")).rejects.toThrow();
  });
  it("refuses a source directory without its sync manifest", async () => {
    vi.stubEnv("LATEXDO_AI_SOURCE_PATH", path.join(fixture.root, "absent"));
    await expect(run("sync-ai.mjs")).rejects.toThrow("No AI source manifest");
  });
  it("validates source and target files and fragment boundaries", async () => {
    const manifest = {
      schemaVersion: 1,
      files: [{ from: "a.ts", to: "b.ts" }],
      styleFragments: [
        {
          from: "fragment.css",
          to: "style.css",
          startMarker: "/* AI */",
          endMarker: "/* END */",
        },
      ],
    };
    const file = await write("sync.json", manifest);
    await write("a.ts", "source");
    await write("b.ts", "target");
    await write("fragment.css", "/* AI */\ncss");
    await write("style.css", "prefix\n/* AI */\ncss\n/* END */\nsuffix");
    await expect(run("validate-sync.mjs", file)).resolves.toBeUndefined();
    await write("style.css", "no markers");
    await expect(run("validate-sync.mjs", file)).rejects.toThrow(
      "valid AI style section",
    );
    await write("fragment.css", "no markers");
    await expect(run("validate-sync.mjs", file)).rejects.toThrow("start marker");
    await write("fragment.css", "/* AI */ /* END */");
    await expect(run("validate-sync.mjs", file)).rejects.toThrow("host end marker");
  });
  it.each([
    {
      schemaVersion: 1,
      files: [
        { from: "a", to: "b" },
        { from: "a", to: "b" },
      ],
    },
    { schemaVersion: 1, files: [{ from: "missing", to: "b" }] },
    { schemaVersion: 1, files: [{ from: "a", to: "missing" }] },
    { schemaVersion: 1, files: [{ from: "/outside", to: "b" }] },
  ])("rejects duplicate, missing or escaping sync paths %j", async (manifest) => {
    await write("a", "source");
    await write("b", "target");
    const file = await write("sync.json", manifest);
    await expect(run("validate-sync.mjs", file)).rejects.toThrow();
  });
});
