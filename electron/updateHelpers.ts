export const windowsUpdateHelper = [
  "$ErrorActionPreference = 'Stop'",
  "$logFile = $env:LATEXDO_UPDATE_LOG",
  "New-Item -ItemType Directory -Force -Path (Split-Path -Parent $logFile) | Out-Null",
  "function Write-Log {",
  "  param([string]$Message)",
  "  # Windows PowerShell 5.1 defaults to the ANSI code page, which garbles non-ASCII paths.",
  '  Add-Content -LiteralPath $logFile -Encoding UTF8 -Value ("[{0:u}] {1}" -f (Get-Date), $Message)',
  "}",
  "function Test-LatexDoVersionMatch {",
  "  param([string]$Installed, [string]$Expected)",
  "  function Get-VersionParts {",
  "    param([string]$Value)",
  "    $normalized = $Value.Trim()",
  "    if ($normalized -match '^[vV]') { $normalized = $normalized.Substring(1) }",
  "    $hyphenIndex = $normalized.IndexOf('-')",
  "    if ($hyphenIndex -ge 0) {",
  "      $coreText = $normalized.Substring(0, $hyphenIndex)",
  "      $prereleaseText = $normalized.Substring($hyphenIndex + 1)",
  "    } else {",
  "      $coreText = $normalized",
  "      $prereleaseText = ''",
  "    }",
  "    $prerelease = @()",
  "    if ($prereleaseText -ne '') {",
  "      $prerelease = @($prereleaseText -split '[.-]' | Where-Object { $_ -ne '' })",
  "    }",
  "    return @{ Core = @($coreText -split '\\.' | Where-Object { $_ -ne '' }); Prerelease = @($prerelease) }",
  "  }",
  "  function Compare-VersionPart {",
  "    param([string]$Left, [string]$Right)",
  "    $leftLong = 0L",
  "    $rightLong = 0L",
  "    $leftNumeric = [long]::TryParse($Left, [ref]$leftLong)",
  "    $rightNumeric = [long]::TryParse($Right, [ref]$rightLong)",
  "    if ($leftNumeric -and $rightNumeric) {",
  "      if ($leftLong -eq $rightLong) { return 0 }",
  "      if ($leftLong -gt $rightLong) { return 1 }",
  "      return -1",
  "    }",
  "    if ($Left -eq $Right) { return 0 }",
  "    if ($Left -gt $Right) { return 1 }",
  "    return -1",
  "  }",
  "  $installedParts = Get-VersionParts -Value $Installed",
  "  $expectedParts = Get-VersionParts -Value $Expected",
  "  $coreLength = [Math]::Max($installedParts.Core.Count, $expectedParts.Core.Count)",
  "  for ($index = 0; $index -lt $coreLength; $index += 1) {",
  "    $leftPart = if ($index -lt $installedParts.Core.Count) { $installedParts.Core[$index] } else { '0' }",
  "    $rightPart = if ($index -lt $expectedParts.Core.Count) { $expectedParts.Core[$index] } else { '0' }",
  "    if ((Compare-VersionPart -Left $leftPart -Right $rightPart) -ne 0) { return $false }",
  "  }",
  "  if ($installedParts.Prerelease.Count -eq 0 -or $expectedParts.Prerelease.Count -eq 0) {",
  "    return $installedParts.Prerelease.Count -eq $expectedParts.Prerelease.Count",
  "  }",
  "  $prereleaseLength = [Math]::Max($installedParts.Prerelease.Count, $expectedParts.Prerelease.Count)",
  "  for ($preIndex = 0; $preIndex -lt $prereleaseLength; $preIndex += 1) {",
  "    if ($preIndex -ge $installedParts.Prerelease.Count) { return $false }",
  "    if ($preIndex -ge $expectedParts.Prerelease.Count) { return $false }",
  "    if ((Compare-VersionPart -Left $installedParts.Prerelease[$preIndex] -Right $expectedParts.Prerelease[$preIndex]) -ne 0) { return $false }",
  "  }",
  "  return $true",
  "}",
  "function Test-SafeInstallDirectory {",
  "  param([string]$Directory)",
  "  if (-not $Directory) { return $false }",
  "  $trimmed = $Directory.TrimEnd('\\')",
  "  $root = [System.IO.Path]::GetPathRoot($Directory)",
  "  if (-not $root) { return $false }",
  "  return $trimmed.Length -gt $root.TrimEnd('\\').Length",
  "}",
  "function Get-InstallDirectoryProcesses {",
  "  param([string]$Directory)",
  "  if (-not (Test-SafeInstallDirectory -Directory $Directory)) { return @() }",
  "  $prefix = $Directory.TrimEnd('\\') + '\\'",
  "  try {",
  "    return @(Get-CimInstance -ClassName Win32_Process -ErrorAction Stop | Where-Object {",
  "      $_.ProcessId -ne $PID -and $_.ExecutablePath -and $_.ExecutablePath.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)",
  "    })",
  "  } catch {",
  '    Write-Log ("Could not list running processes: {0}" -f $_.Exception.Message)',
  "    return @()",
  "  }",
  "}",
  "function Wait-ForProcessExit {",
  "  param([int]$ProcessId, [int]$TimeoutSeconds)",
  "  if ($ProcessId -le 0) { return $true }",
  "  $deadline = (Get-Date).AddSeconds($TimeoutSeconds)",
  "  while (Get-Process -Id $ProcessId -ErrorAction SilentlyContinue) {",
  "    if ((Get-Date) -ge $deadline) { return $false }",
  "    Start-Sleep -Milliseconds 250",
  "  }",
  "  return $true",
  "}",
  "function Stop-InstallDirectoryProcesses {",
  "  param([string]$Directory, [int]$GraceSeconds)",
  "  $deadline = (Get-Date).AddSeconds($GraceSeconds)",
  "  while ((Get-InstallDirectoryProcesses -Directory $Directory).Count -gt 0) {",
  "    if ((Get-Date) -ge $deadline) { break }",
  "    Start-Sleep -Milliseconds 500",
  "  }",
  "  $remaining = Get-InstallDirectoryProcesses -Directory $Directory",
  "  foreach ($stray in $remaining) {",
  '    Write-Log ("Stopping {0} (PID {1}) still running from the install directory" -f $stray.Name, $stray.ProcessId)',
  "    Stop-Process -Id $stray.ProcessId -Force -ErrorAction SilentlyContinue",
  "  }",
  "  if ($remaining.Count -gt 0) { Start-Sleep -Seconds 2 }",
  "}",
  "function Write-RelatedProcesses {",
  "  param([int]$RootProcessId, [string]$Directory, [string]$Label)",
  "  try {",
  "    $all = @(Get-CimInstance -ClassName Win32_Process -ErrorAction Stop)",
  "    $tree = @{}",
  "    $tree[$RootProcessId] = $true",
  "    do {",
  "      $added = $false",
  "      foreach ($candidate in $all) {",
  "        if (-not $tree.ContainsKey([int]$candidate.ProcessId) -and $tree.ContainsKey([int]$candidate.ParentProcessId)) {",
  "          $tree[[int]$candidate.ProcessId] = $true",
  "          $added = $true",
  "        }",
  "      }",
  "    } while ($added)",
  "    foreach ($candidate in $all) {",
  "      if ([int]$candidate.ProcessId -eq $PID) { continue }",
  "      $mentionsDirectory = $Directory -and $candidate.CommandLine -and $candidate.CommandLine.IndexOf($Directory, [System.StringComparison]::OrdinalIgnoreCase) -ge 0",
  "      if ($tree.ContainsKey([int]$candidate.ProcessId) -or $mentionsDirectory) {",
  '        Write-Log ("{0} PID={1} Parent={2} Name={3} CommandLine={4}" -f $Label, $candidate.ProcessId, $candidate.ParentProcessId, $candidate.Name, $candidate.CommandLine)',
  "      }",
  "    }",
  "  } catch {",
  '    Write-Log ("Could not list running processes: {0}" -f $_.Exception.Message)',
  "  }",
  "}",
  "function Invoke-LatexDoInstaller {",
  "  param([string]$Installer, [string]$Directory)",
  "  # --updated is how electron-builder's NSIS installer expects silent updates: it keeps",
  "  # the user's shortcuts and restores the previous files if replacing them fails.",
  "  # /D= must be the last argument and must not be quoted.",
  '  $arguments = "--updated /S /D=$Directory"',
  '  Write-Log ("InstallerArgs={0}" -f $arguments)',
  "  $installStartedAt = Get-Date",
  "  # Start-Process -Wait also waits for every process the installer starts, so one that",
  "  # outlives it would block the update forever. Wait for the installer itself, bounded.",
  "  $process = Start-Process -FilePath $Installer -ArgumentList $arguments -WorkingDirectory (Split-Path -Parent $Installer) -PassThru",
  '  try { $null = $process.Handle } catch { Write-Log ("Could not open installer handle: {0}" -f $_.Exception.Message) }',
  '  Write-Log ("InstallerPid={0}" -f $process.Id)',
  "  if (-not $process.WaitForExit($installerTimeoutSeconds * 1000)) {",
  '    Write-Log ("Installer is still running after {0} seconds" -f $installerTimeoutSeconds)',
  "    Write-RelatedProcesses -RootProcessId $process.Id -Directory $Directory -Label 'StuckProcess'",
  "    & taskkill.exe /PID $process.Id /T /F | Out-Null",
  '    throw "Installer did not finish within $installerTimeoutSeconds seconds."',
  "  }",
  "  Write-RelatedProcesses -RootProcessId $process.Id -Directory $Directory -Label 'LeftoverProcess'",
  '  Write-Log ("InstallStart={0:u}" -f $installStartedAt)',
  '  Write-Log ("InstallFinish={0:u}" -f (Get-Date))',
  '  Write-Log ("InstallerExitCode={0}" -f $process.ExitCode)',
  "  return $process.ExitCode",
  "}",
  "$helperRoot = $PSScriptRoot",
  "$appPid = 0",
  "$installer = $env:LATEXDO_UPDATE_INSTALLER",
  "$targetExe = $env:LATEXDO_UPDATE_TARGET_EXE",
  "$targetDirectory = $null",
  "$installerTimeoutSeconds = 600",
  "if ($targetExe) { $targetDirectory = Split-Path -Parent $targetExe }",
  "try {",
  "  Write-Log 'Starting Windows update helper'",
  '  Write-Log ("CurrentProcess={0}" -f $PID)',
  '  Write-Log ("ExpectedVersion={0}" -f $env:LATEXDO_UPDATE_EXPECTED_VERSION)',
  '  Write-Log ("Installer={0}" -f $installer)',
  '  Write-Log ("TargetExe={0}" -f $targetExe)',
  "  $expectedVersion = $env:LATEXDO_UPDATE_EXPECTED_VERSION",
  "  if (-not $expectedVersion) {",
  '    throw "Expected update version was not provided (LATEXDO_UPDATE_EXPECTED_VERSION)."',
  "  }",
  "  if ($env:LATEXDO_UPDATE_INSTALLER_TIMEOUT_SECONDS) {",
  "    $installerTimeoutSeconds = [int]$env:LATEXDO_UPDATE_INSTALLER_TIMEOUT_SECONDS",
  "  }",
  "  if (-not (Test-SafeInstallDirectory -Directory $targetDirectory)) {",
  '    throw "Install directory is not usable: $targetDirectory"',
  "  }",
  "  $appPid = [int]$env:LATEXDO_UPDATE_APP_PID",
  '  Write-Log ("Waiting for PID {0}" -f $appPid)',
  "  # Quitting saves open tabs first, so allow well over the old 60 second limit.",
  "  if (-not (Wait-ForProcessExit -ProcessId $appPid -TimeoutSeconds 300)) {",
  '    throw "LatexDo (PID $appPid) did not exit within 5 minutes."',
  "  }",
  "  # Renderer, GPU and terminal helpers can outlive the main process and keep files in",
  "  # the install directory locked, which makes the installer fail.",
  "  Stop-InstallDirectoryProcesses -Directory $targetDirectory -GraceSeconds 15",
  "  if (-not (Test-Path -LiteralPath $installer)) {",
  '    throw "Installer is missing: $installer"',
  "  }",
  "  $installerExitCode = Invoke-LatexDoInstaller -Installer $installer -Directory $targetDirectory",
  "  if ($installerExitCode -ne 0) {",
  "    Write-Log 'Installer failed; stopping leftover processes and retrying once'",
  "    Stop-InstallDirectoryProcesses -Directory $targetDirectory -GraceSeconds 0",
  "    Start-Sleep -Seconds 3",
  "    $installerExitCode = Invoke-LatexDoInstaller -Installer $installer -Directory $targetDirectory",
  "  }",
  "  if ($installerExitCode -ne 0) {",
  '    throw "Installer exited with code $installerExitCode"',
  "  }",
  "  if (-not (Test-Path -LiteralPath $targetExe)) {",
  '    throw "Installed executable was not found: $targetExe"',
  "  }",
  "  $item = Get-Item -LiteralPath $targetExe",
  "  $installedVersion = $item.VersionInfo.ProductVersion",
  "  $installedFileVersion = $item.VersionInfo.FileVersion",
  '  Write-Log ("TargetProductVersion={0}" -f $installedVersion)',
  '  Write-Log ("TargetFileVersion={0}" -f $installedFileVersion)',
  "  if (-not $installedVersion) {",
  '    throw "Could not determine installed executable version."',
  "  }",
  "  $versionMatches = Test-LatexDoVersionMatch -Installed $installedVersion -Expected $expectedVersion",
  '  Write-Log ("VersionMatch={0} ExpectedVersion={1} InstalledVersion={2}" -f $versionMatches, $expectedVersion, $installedVersion)',
  "  if (-not $versionMatches) {",
  '    throw "Installed executable ProductVersion $installedVersion does not match expected update version $expectedVersion."',
  "  }",
  "  $receipt = Join-Path $helperRoot 'version-receipt'",
  '  $probeArgs = \'--latexdo-verify-update "{0}" "{1}"\' -f $expectedVersion, $receipt',
  "  $probe = Start-Process -FilePath $targetExe -ArgumentList $probeArgs -WorkingDirectory $targetDirectory -PassThru",
  "  # Windows PowerShell 5.1 leaves ExitCode empty after WaitForExit(timeout) unless the",
  "  # process handle was read first, which made every verification fail.",
  '  try { $null = $probe.Handle } catch { Write-Log ("Could not open probe handle: {0}" -f $_.Exception.Message) }',
  "  if (-not $probe.WaitForExit(60000)) {",
  "    Stop-Process -Id $probe.Id -Force -ErrorAction SilentlyContinue",
  "    throw 'Installed application version probe timed out.'",
  "  }",
  "  $probeExitCode = $probe.ExitCode",
  '  Write-Log ("ProbeExitCode={0}" -f $probeExitCode)',
  "  # The receipt is the proof: the probe writes it only when the packaged version matches.",
  "  if (-not (Test-Path -LiteralPath $receipt)) {",
  "    throw 'Installed application did not confirm its packaged version.'",
  "  }",
  "  if ($null -ne $probeExitCode -and $probeExitCode -ne 0) {",
  '    throw "Installed application version probe exited with code $probeExitCode."',
  "  }",
  "  if ((Get-Content -LiteralPath $receipt -Raw).Trim() -ne $expectedVersion) {",
  "    throw 'Installed application version receipt does not match.'",
  "  }",
  '  Write-Log ("Verification=PASS ExpectedVersion={0} InstalledVersion={1}" -f $expectedVersion, $installedVersion)',
  "  $relaunched = Start-Process -FilePath $targetExe -WorkingDirectory $targetDirectory -PassThru",
  '  Write-Log ("RelaunchedPid={0}" -f $relaunched.Id)',
  '  Write-Log ("Verified and launched LatexDo {0}" -f $installedVersion)',
  "  Write-Log 'Windows update helper finished'",
  "} catch {",
  '  Set-Content -LiteralPath $env:LATEXDO_UPDATE_FAILURE_FILE -Value ("Update failed: {0}" -f $_.Exception.Message) -Encoding UTF8',
  '  Write-Log ("Verification=FAIL Reason={0}" -f $_.Exception.Message)',
  '  Write-Log ("Windows update helper failed: {0}" -f $_.Exception.Message)',
  "  try {",
  "    # Reopening while the old process is still shutting down would only focus it.",
  "    if (-not (Wait-ForProcessExit -ProcessId $appPid -TimeoutSeconds 60)) {",
  "      Write-Log 'LatexDo is still running; not reopening it'",
  "    } else {",
  "      if ($targetExe -and -not (Test-Path -LiteralPath $targetExe) -and $installer -and (Test-Path -LiteralPath $installer)) {",
  "        Write-Log 'Application executable is missing; running the installer once more to repair it'",
  "        Stop-InstallDirectoryProcesses -Directory $targetDirectory -GraceSeconds 0",
  "        $null = Invoke-LatexDoInstaller -Installer $installer -Directory $targetDirectory",
  "      }",
  "      if ($targetExe -and (Test-Path -LiteralPath $targetExe)) {",
  "        $reopened = Start-Process -FilePath $targetExe -WorkingDirectory $targetDirectory -PassThru",
  '        Write-Log ("ReopenedPid={0}" -f $reopened.Id)',
  "      } else {",
  '        Write-Log ("Could not reopen application: {0} is missing" -f $targetExe)',
  "      }",
  "    }",
  "  } catch {",
  '    Write-Log ("Could not reopen application after failure: {0}" -f $_.Exception.Message)',
  "  }",
  "  exit 1",
  "} finally {",
  "  Start-Sleep -Seconds 2",
  "  Remove-Item -LiteralPath $helperRoot -Recurse -Force -ErrorAction SilentlyContinue",
  "}",
  "",
].join("\r\n");
